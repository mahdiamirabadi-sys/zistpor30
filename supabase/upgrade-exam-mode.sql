CREATE OR REPLACE FUNCTION porseman_private.fetch_question_rows()
RETURNS SETOF jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
BEGIN
  IF (SELECT auth.uid()) IS NULL OR NOT EXISTS (
    SELECT 1
    FROM public.profiles p
    WHERE p.id = (SELECT auth.uid())
      AND p.role = 'student'
      AND p.is_approved IS TRUE
  ) THEN
    RAISE EXCEPTION 'حساب دانش‌آموز تأیید نشده یا ورود انجام نشده است.'
      USING ERRCODE = '42501';
  END IF;

  RETURN QUERY
  SELECT pg_catalog.jsonb_build_object(
    'id', q.id,
    'question_code', q.question_code,
    'book', q.book,
    'chapter', q.chapter,
    'lesson', q.lesson,
    'topic', q.topic,
    'statement', q.statement
  )
  FROM public.questions q
  WHERE q.is_active IS TRUE
  ORDER BY q.id;
END;
$$;

REVOKE ALL ON FUNCTION porseman_private.fetch_question_rows() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION porseman_private.fetch_question_rows() TO authenticated;

