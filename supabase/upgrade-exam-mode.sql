-- 7) آزمون: ثبت پاسخ بدون اعلام درست یا غلط بودن
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION porseman_private.submit_exam_answer(
  p_session_id uuid,
  p_question_id bigint,
  p_selected_answer boolean
)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_uid uuid;
  v_answered integer;
  v_total integer;
BEGIN
  v_uid := (SELECT auth.uid());

  IF v_uid IS NULL OR NOT EXISTS (
    SELECT 1
    FROM public.profiles p
    WHERE p.id = v_uid
      AND p.role = 'student'
      AND p.is_approved IS TRUE
  ) THEN
    RAISE EXCEPTION 'حساب دانش‌آموز مجاز به ثبت پاسخ آزمون نیست.'
      USING ERRCODE = '42501';
  END IF;

  IF p_session_id IS NULL
     OR p_question_id IS NULL
     OR p_selected_answer IS NULL THEN
    RAISE EXCEPTION 'اطلاعات پاسخ آزمون ناقص است.'
      USING ERRCODE = '22023';
  END IF;

  UPDATE public.exam_session_questions esq
  SET selected_answer = p_selected_answer,
      answered_at = pg_catalog.now()
  FROM public.exam_sessions es
  WHERE esq.session_id = p_session_id
    AND esq.question_id = p_question_id
    AND es.id = esq.session_id
    AND es.student_id = v_uid
    AND es.status = 'in_progress';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'جلسه آزمون فعال نیست یا این سؤال متعلق به آزمون شما نیست.'
      USING ERRCODE = '42501';
  END IF;

  SELECT
    count(*) FILTER (WHERE esq.selected_answer IS NOT NULL),
    count(*)
  INTO v_answered, v_total
  FROM public.exam_session_questions esq
  WHERE esq.session_id = p_session_id;

  -- عمداً هیچ پاسخ صحیح یا نتیجه‌ای در این تابع برگردانده نمی‌شود.
  RETURN pg_catalog.jsonb_build_object(
    'saved', true,
    'answered', v_answered,
    'total', v_total
  );
END;
$$;

REVOKE ALL ON FUNCTION porseman_private.submit_exam_answer(uuid, bigint, boolean)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION porseman_private.submit_exam_answer(uuid, bigint, boolean)
  TO authenticated;

