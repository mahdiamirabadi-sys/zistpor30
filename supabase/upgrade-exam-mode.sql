BEGIN;

-- ------------------------------------------------------------
-- 1) زیرساخت و تابع تشخیص دبیر
-- ------------------------------------------------------------

CREATE SCHEMA IF NOT EXISTS porseman_private;
REVOKE ALL ON SCHEMA porseman_private FROM PUBLIC, anon;
GRANT USAGE ON SCHEMA porseman_private TO authenticated;

CREATE OR REPLACE FUNCTION porseman_private.is_teacher()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
  SELECT EXISTS (
    SELECT 1
    FROM public.profiles p
    WHERE p.id = (SELECT auth.uid())
      AND p.role = 'teacher'
  );
$$;

REVOKE ALL ON FUNCTION porseman_private.is_teacher() FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION porseman_private.is_teacher() TO authenticated;

-- ------------------------------------------------------------
-- 2) جدول‌های آزمون
-- ------------------------------------------------------------

CREATE TABLE IF NOT EXISTS public.exam_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id uuid NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
  status text NOT NULL DEFAULT 'in_progress'
    CHECK (status IN ('in_progress', 'submitted', 'cancelled')),
  book text,
  chapter text,
  lesson text,
  topic text,
  question_count integer NOT NULL CHECK (question_count > 0),
  correct_count integer,
  wrong_count integer,
  unanswered_count integer,
  score_percent numeric(5,2),
  started_at timestamptz NOT NULL DEFAULT now(),
  submitted_at timestamptz,
  ended_at timestamptz
);

CREATE TABLE IF NOT EXISTS public.exam_session_questions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  session_id uuid NOT NULL
    REFERENCES public.exam_sessions(id) ON DELETE CASCADE,
  question_id bigint NOT NULL
    REFERENCES public.questions(id) ON DELETE RESTRICT,
  position integer NOT NULL CHECK (position > 0),
  selected_answer boolean,
  answered_at timestamptz,
  is_correct boolean,
  CONSTRAINT exam_session_questions_unique_question
    UNIQUE (session_id, question_id),
  CONSTRAINT exam_session_questions_unique_position
    UNIQUE (session_id, position)
);

CREATE INDEX IF NOT EXISTS exam_sessions_student_started_idx
  ON public.exam_sessions(student_id, started_at DESC);

CREATE INDEX IF NOT EXISTS exam_session_questions_session_position_idx
  ON public.exam_session_questions(session_id, position);

CREATE UNIQUE INDEX IF NOT EXISTS exam_sessions_one_active_per_student
  ON public.exam_sessions(student_id)
  WHERE status = 'in_progress';

ALTER TABLE public.exam_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.exam_session_questions ENABLE ROW LEVEL SECURITY;

-- ------------------------------------------------------------
-- 3) حذف سیاست‌های قدیمی و تعریف دسترسی‌های یکدست
-- ------------------------------------------------------------

DO $$
DECLARE
  r record;
BEGIN
  FOR r IN
    SELECT schemaname, tablename, policyname
    FROM pg_policies
    WHERE schemaname = 'public'
      AND tablename IN (
        'questions',
        'attempts',
        'profiles',
        'exam_sessions',
        'exam_session_questions'
      )
  LOOP
    EXECUTE format(
      'DROP POLICY IF EXISTS %I ON %I.%I',
      r.policyname,
      r.schemaname,
      r.tablename
    );
  END LOOP;
END;
$$;

ALTER TABLE public.questions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.attempts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;

-- جدول سؤال‌ها: دسترسی مستقیم فقط برای دبیر.
-- دانش‌آموز صورت سؤال را فقط از تابع امن get_practice_questions می‌گیرد.
CREATE POLICY pz_questions_teacher_select
  ON public.questions
  FOR SELECT TO authenticated
  USING (porseman_private.is_teacher());

CREATE POLICY pz_questions_teacher_insert
  ON public.questions
  FOR INSERT TO authenticated
  WITH CHECK (porseman_private.is_teacher());

CREATE POLICY pz_questions_teacher_update
  ON public.questions
  FOR UPDATE TO authenticated
  USING (porseman_private.is_teacher())
  WITH CHECK (porseman_private.is_teacher());

-- پروفایل: هر کاربر فقط پروفایل خودش را می‌خواند؛ دبیر همه را می‌خواند و به‌روزرسانی می‌کند.
CREATE POLICY pz_profiles_select
  ON public.profiles
  FOR SELECT TO authenticated
  USING (id = (SELECT auth.uid()) OR porseman_private.is_teacher());

CREATE POLICY pz_profiles_teacher_update
  ON public.profiles
  FOR UPDATE TO authenticated
  USING (porseman_private.is_teacher())
  WITH CHECK (porseman_private.is_teacher());

-- پاسخ‌های تمرینی: دانش‌آموز سوابق خودش و دبیر همه سوابق را می‌بیند.
-- هیچ سیاست INSERT/UPDATE مستقیمی وجود ندارد؛ ثبت فقط از RPC امن انجام می‌شود.
CREATE POLICY pz_attempts_select
  ON public.attempts
  FOR SELECT TO authenticated
  USING (
    student_id = (SELECT auth.uid())
    OR porseman_private.is_teacher()
  );

-- اطلاعات آزمون فقط برای گزارش دبیر مستقیماً قابل خواندن است.
-- دانش‌آموز از توابع RPC نتیجه آزمون خودش را دریافت می‌کند.
CREATE POLICY pz_exam_sessions_teacher_select
  ON public.exam_sessions
  FOR SELECT TO authenticated
  USING (porseman_private.is_teacher());

CREATE POLICY pz_exam_session_questions_teacher_select
  ON public.exam_session_questions
  FOR SELECT TO authenticated
  USING (porseman_private.is_teacher());

-- مجوزهای جدول؛ سیاست RLS همچنان دسترسی ردیفی را کنترل می‌کند.
REVOKE ALL ON TABLE public.questions, public.attempts, public.profiles
  FROM anon, authenticated;

GRANT SELECT, INSERT, UPDATE ON TABLE public.questions TO authenticated;
GRANT SELECT, UPDATE ON TABLE public.profiles TO authenticated;
GRANT SELECT ON TABLE public.attempts TO authenticated;

REVOKE ALL ON TABLE public.exam_sessions, public.exam_session_questions
  FROM anon, authenticated;
GRANT SELECT ON TABLE public.exam_sessions, public.exam_session_questions
  TO authenticated;

