CREATE OR REPLACE FUNCTION porseman_private.cancel_exam(
  p_session_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_uid uuid;
BEGIN
  v_uid := (SELECT auth.uid());

  IF v_uid IS NULL OR NOT EXISTS (
    SELECT 1
    FROM public.profiles p
    WHERE p.id = v_uid
      AND p.role = 'student'
      AND p.is_approved IS TRUE
  ) THEN
    RAISE EXCEPTION 'دسترسی به لغو آزمون مجاز نیست.'
      USING ERRCODE = '42501';
  END IF;

  UPDATE public.exam_sessions
  SET status = 'cancelled',
      ended_at = pg_catalog.now()
  WHERE id = p_session_id
    AND student_id = v_uid
    AND status = 'in_progress';

  IF NOT FOUND THEN
    RAISE EXCEPTION 'آزمون فعال برای لغو پیدا نشد.'
      USING ERRCODE = '22023';
  END IF;

  RETURN pg_catalog.jsonb_build_object('cancelled', true);
END;
$$;

