CREATE OR REPLACE FUNCTION porseman_private.grade_and_save_answer(
  p_question_id text,
  p_selected_answer boolean
)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_question public.questions%ROWTYPE;
  v_correct boolean;
  v_uid uuid;
BEGIN
  v_uid := (SELECT auth.uid());

  IF v_uid IS NULL OR NOT EXISTS (
    SELECT 1
    FROM public.profiles p
    WHERE p.id = v_uid
      AND p.role = 'student'
      AND p.is_approved IS TRUE
  ) THEN
    RAISE EXCEPTION 'دسترسی به ثبت پاسخ مجاز نیست.'
      USING ERRCODE = '42501';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.exam_sessions es
    WHERE es.student_id = v_uid
      AND es.status = 'in_progress'
  ) THEN
    RAISE EXCEPTION 'تا پایان یا لغو آزمون، امکان استفاده از تمرین وجود ندارد.'
      USING ERRCODE = '42501';
  END IF;

  IF p_question_id IS NULL
     OR p_question_id !~ '^[0-9]+$'
     OR p_selected_answer IS NULL THEN
    RAISE EXCEPTION 'درخواست پاسخ‌گویی نامعتبر است.'
      USING ERRCODE = '22023';
  END IF;

  SELECT *
  INTO v_question
  FROM public.questions q
  WHERE q.id = p_question_id::bigint
    AND q.is_active IS TRUE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'سؤال فعال پیدا نشد.'
      USING ERRCODE = '22023';
  END IF;

  v_correct := (v_question.is_true = p_selected_answer);

  INSERT INTO public.attempts (
    student_id,
    question_id,
    selected_answer,
    is_correct
  )
  VALUES (
    v_uid,
    v_question.id,
    p_selected_answer,
    v_correct
  );

  RETURN pg_catalog.jsonb_build_object(
    'correct', v_correct,
    'correct_answer', v_question.is_true,
    'correction',
      CASE WHEN v_question.is_true THEN NULL ELSE v_question.correction END
  );
END;
$$;

REVOKE ALL ON FUNCTION porseman_private.grade_and_save_answer(text, boolean)
  FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION porseman_private.grade_and_save_answer(text, boolean)
  TO authenticated;

