-- ------------------------------------------------------------
-- 6) آزمون: شروع جلسه و انتخاب تصادفی سؤال‌ها در سمت سرور
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION porseman_private.start_exam(
  p_question_count integer,
  p_book text DEFAULT NULL,
  p_chapter text DEFAULT NULL,
  p_lesson text DEFAULT NULL,
  p_topic text DEFAULT NULL
)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_uid uuid;
  v_available integer;
  v_session_id uuid;
  v_question_payload jsonb;
BEGIN
  v_uid := (SELECT auth.uid());

  IF v_uid IS NULL OR NOT EXISTS (
    SELECT 1
    FROM public.profiles p
    WHERE p.id = v_uid
      AND p.role = 'student'
      AND p.is_approved IS TRUE
  ) THEN
    RAISE EXCEPTION 'حساب دانش‌آموز تأیید نشده است.'
      USING ERRCODE = '42501';
  END IF;

  IF p_question_count IS NULL OR p_question_count < 1 THEN
    RAISE EXCEPTION 'تعداد سؤال آزمون باید حداقل یک باشد.'
      USING ERRCODE = '22023';
  END IF;

  SELECT count(*)
  INTO v_available
  FROM public.questions q
  WHERE q.is_active IS TRUE
    AND (p_book IS NULL OR q.book = p_book)
    AND (p_chapter IS NULL OR q.chapter = p_chapter)
    AND (p_lesson IS NULL OR q.lesson = p_lesson)
    AND (p_topic IS NULL OR q.topic = p_topic);

  IF v_available < p_question_count THEN
    RAISE EXCEPTION 'تعداد سؤال‌های فعال این محدوده کافی نیست. تعداد موجود: %',
      v_available
      USING ERRCODE = '22023';
  END IF;

  -- اگر دانش‌آموز از آزمون قبلی خارج شده باشد، جلسه ناتمام قبلی لغو می‌شود.
  UPDATE public.exam_sessions
  SET status = 'cancelled',
      ended_at = pg_catalog.now()
  WHERE student_id = v_uid
    AND status = 'in_progress';

  INSERT INTO public.exam_sessions (
    student_id,
    status,
    book,
    chapter,
    lesson,
    topic,
    question_count
  )
  VALUES (
    v_uid,
    'in_progress',
    p_book,
    p_chapter,
    p_lesson,
    p_topic,
    p_question_count
  )
  RETURNING id INTO v_session_id;

  WITH picked AS (
    SELECT
      chosen.id,
      row_number() OVER (ORDER BY pg_catalog.random())::integer AS position
    FROM (
      SELECT q.id
      FROM public.questions q
      WHERE q.is_active IS TRUE
        AND (p_book IS NULL OR q.book = p_book)
        AND (p_chapter IS NULL OR q.chapter = p_chapter)
        AND (p_lesson IS NULL OR q.lesson = p_lesson)
        AND (p_topic IS NULL OR q.topic = p_topic)
      ORDER BY pg_catalog.random()
      LIMIT p_question_count
    ) AS chosen
  )
  INSERT INTO public.exam_session_questions (
    session_id,
    question_id,
    position
  )
  SELECT v_session_id, picked.id, picked.position
  FROM picked;

  SELECT COALESCE(
    pg_catalog.jsonb_agg(
      pg_catalog.jsonb_build_object(
        'id', q.id,
        'question_code', q.question_code,
        'book', q.book,
        'chapter', q.chapter,
        'lesson', q.lesson,
        'topic', q.topic,
        'statement', q.statement,
        'position', esq.position
      )
      ORDER BY esq.position
    ),
    '[]'::jsonb
  )
  INTO v_question_payload
  FROM public.exam_session_questions esq
  JOIN public.questions q ON q.id = esq.question_id
  WHERE esq.session_id = v_session_id;

  RETURN pg_catalog.jsonb_build_object(
    'session_id', v_session_id,
    'questions', v_question_payload
  );
END;
$$;

