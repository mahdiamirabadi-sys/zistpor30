-- ------------------------------------------------------------
-- 8) آزمون: محاسبه و نمایش کارنامه فقط در پایان
-- ------------------------------------------------------------

CREATE OR REPLACE FUNCTION porseman_private.finish_exam(
  p_session_id uuid
)
RETURNS jsonb
LANGUAGE plpgsql
VOLATILE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_uid uuid;
  v_session public.exam_sessions%ROWTYPE;
  v_total integer;
  v_correct integer;
  v_unanswered integer;
  v_question_payload jsonb;
BEGIN
  v_uid := (SELECT auth.uid());

  IF v_uid IS NULL OR NOT EXISTS (
    SELECT 1
    FROM public.profiles p
    WHERE p.id = v_uid
      AND p.role = 'student'
      AND p.is_approved IS TRUE
  ) THEN
    RAISE EXCEPTION 'دسترسی به کارنامه آزمون مجاز نیست.'
      USING ERRCODE = '42501';
  END IF;

  SELECT *
  INTO v_session
  FROM public.exam_sessions es
  WHERE es.id = p_session_id
    AND es.student_id = v_uid
  FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'جلسه آزمون پیدا نشد.'
      USING ERRCODE = '42501';
  END IF;

  IF v_session.status = 'cancelled' THEN
    RAISE EXCEPTION 'این آزمون لغو شده و کارنامه ندارد.'
      USING ERRCODE = '22023';
  END IF;

  IF v_session.status = 'in_progress' THEN
    UPDATE public.exam_session_questions esq
    SET is_correct = COALESCE(esq.selected_answer = q.is_true, FALSE)
    FROM public.questions q
    WHERE esq.session_id = p_session_id
      AND q.id = esq.question_id;

    SELECT
      count(*),
      count(*) FILTER (WHERE esq.is_correct IS TRUE),
      count(*) FILTER (WHERE esq.selected_answer IS NULL)
    INTO v_total, v_correct, v_unanswered
    FROM public.exam_session_questions esq
    WHERE esq.session_id = p_session_id;

    UPDATE public.exam_sessions
    SET status = 'submitted',
        submitted_at = pg_catalog.now(),
        ended_at = pg_catalog.now(),
        correct_count = v_correct,
        wrong_count = v_total - v_correct,
        unanswered_count = v_unanswered,
        score_percent = CASE
          WHEN v_total > 0
            THEN round((v_correct::numeric * 100) / v_total, 2)
          ELSE 0
        END
    WHERE id = p_session_id
    RETURNING * INTO v_session;
  END IF;

  SELECT COALESCE(
    pg_catalog.jsonb_agg(
      pg_catalog.jsonb_build_object(
        'id', q.id,
        'position', esq.position,
        'statement', q.statement,
        'selected_answer', esq.selected_answer,
        'correct_answer', q.is_true,
        'is_correct', COALESCE(esq.is_correct, FALSE),
        'correction',
          CASE WHEN q.is_true THEN NULL ELSE q.correction END,
        'explanation', q.explanation
      )
      ORDER BY esq.position
    ),
    '[]'::jsonb
  )
  INTO v_question_payload
  FROM public.exam_session_questions esq
  JOIN public.questions q ON q.id = esq.question_id
  WHERE esq.session_id = p_session_id;

  RETURN pg_catalog.jsonb_build_object(
    'session_id', v_session.id,
    'total', v_session.question_count,
    'correct_count', COALESCE(v_session.correct_count, 0),
    'wrong_count', COALESCE(v_session.wrong_count, 0),
    'unanswered_count', COALESCE(v_session.unanswered_count, 0),
    'score_percent', COALESCE(v_session.score_percent, 0),
    'submitted_at', v_session.submitted_at,
    'questions', v_question_payload
  );
END;
$$;

